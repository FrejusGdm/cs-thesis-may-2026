"""
generate_jobs_tsv_repaired_20260502.py — repaired-data SLURM array manifest.

This manifest targets the May 2, 2026 repaired dataset only. It deliberately
excludes April 2026 experiment folders and T5/PyT5 jobs.

Output columns:
    job_id  tier  experiment  condition  seed  model_key  results_subdir
    similar_lang  direction  save_checkpoint
"""

from __future__ import annotations

import argparse
from pathlib import Path

from generate_jobs_tsv import generate_all_conditions


CONDITIONS_PER_MODEL = 233
PIPELINE_EXPERIMENT = "exp1"
PIPELINE_CONDITION = "RANDOM-10K_STRUCTURED-4K"
PIPELINE_SEED = 42


def add_paper_sweep(
    jobs: list[dict[str, object]],
    *,
    tier: str,
    model_key: str,
    results_subdir: str,
    similar_lang: str,
    direction: str = "forward",
    save_checkpoint: int = 0,
) -> None:
    for experiment, condition, seed in generate_all_conditions():
        jobs.append({
            "tier": tier,
            "experiment": experiment,
            "condition": condition,
            "seed": seed,
            "model_key": model_key,
            "results_subdir": results_subdir,
            "similar_lang": similar_lang,
            "direction": direction,
            "save_checkpoint": save_checkpoint,
        })


def add_pipeline_checkpoint_jobs(jobs: list[dict[str, object]]) -> None:
    for direction in ("forward", "reverse"):
        jobs.append({
            "tier": "TIER2_PIPELINE",
            "experiment": PIPELINE_EXPERIMENT,
            "condition": PIPELINE_CONDITION,
            "seed": PIPELINE_SEED,
            "model_key": "nllb-600m",
            "results_subdir": f"{direction}/nllb-600m",
            "similar_lang": "ewe_Latn",
            "direction": direction,
            "save_checkpoint": 1,
        })


def build_jobs() -> list[dict[str, object]]:
    conditions = generate_all_conditions()
    if len(conditions) != CONDITIONS_PER_MODEL:
        raise AssertionError(f"Expected {CONDITIONS_PER_MODEL} conditions, got {len(conditions)}")

    jobs: list[dict[str, object]] = []

    # Tier 1: paper-critical NLLB-600M forward sweep, no checkpoints.
    add_paper_sweep(
        jobs,
        tier="TIER1_NLLB600_PAPER",
        model_key="nllb-600m",
        results_subdir="nllb-600m",
        similar_lang="ewe_Latn",
    )

    # Tier 2: only the two usable translator checkpoints.
    add_pipeline_checkpoint_jobs(jobs)

    # Tier 3: mBART forward parity with the original paper sweep.
    add_paper_sweep(
        jobs,
        tier="TIER3_MBART_FORWARD",
        model_key="mbart-50",
        results_subdir="mbart-fr",
        similar_lang="fr_XX",
    )
    add_paper_sweep(
        jobs,
        tier="TIER3_MBART_FORWARD",
        model_key="mbart-50",
        results_subdir="mbart-rand",
        similar_lang="none",
    )

    # Tier 4: NLLB-1.3B forward, last because it is the largest model.
    add_paper_sweep(
        jobs,
        tier="TIER4_NLLB13_FORWARD",
        model_key="nllb-1.3b",
        results_subdir="nllb-1.3b",
        similar_lang="ewe_Latn",
    )

    # Tier 5: optional reverse mBART jobs. Kept separate from forward paths.
    add_paper_sweep(
        jobs,
        tier="TIER5_MBART_REVERSE_NICE_TO_HAVE",
        model_key="mbart-50",
        results_subdir="reverse/mbart-fr",
        similar_lang="fr_XX",
        direction="reverse",
    )
    add_paper_sweep(
        jobs,
        tier="TIER5_MBART_REVERSE_NICE_TO_HAVE",
        model_key="mbart-50",
        results_subdir="reverse/mbart-rand",
        similar_lang="none",
        direction="reverse",
    )

    return jobs


def tier_ranges(jobs: list[dict[str, object]]) -> dict[str, str]:
    ranges: dict[str, list[int]] = {}
    for i, job in enumerate(jobs, start=1):
        ranges.setdefault(str(job["tier"]), []).append(i)
    return {tier: f"{ids[0]}-{ids[-1]}" if ids[0] != ids[-1] else str(ids[0])
            for tier, ids in ranges.items()}


def write_jobs(path: Path, jobs: list[dict[str, object]]) -> None:
    lines = []
    for i, job in enumerate(jobs, start=1):
        fields = [
            i,
            job["tier"],
            job["experiment"],
            job["condition"],
            job["seed"],
            job["model_key"],
            job["results_subdir"],
            job["similar_lang"],
            job["direction"],
            job["save_checkpoint"],
        ]
        lines.append("\t".join(str(f) for f in fields))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_ranges(path: Path, ranges: dict[str, str]) -> None:
    lines = [
        "# Generated by experiments/training/hpc/generate_jobs_tsv_repaired_20260502.py",
        "# shellcheck shell=sh",
    ]
    for name, value in ranges.items():
        lines.append(f'{name}="{value}"')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="experiments/training/hpc/jobs_repaired_20260502.tsv")
    parser.add_argument("--ranges-output", default="experiments/training/hpc/jobs_repaired_20260502.ranges.sh")
    args = parser.parse_args()

    jobs = build_jobs()
    ranges = tier_ranges(jobs)
    write_jobs(Path(args.output), jobs)
    write_ranges(Path(args.ranges_output), ranges)

    print(f"Generated {args.output} with {len(jobs)} jobs")
    for tier, array_range in ranges.items():
        start, _, end = array_range.partition("-")
        count = int(end or start) - int(start) + 1
        print(f"  {tier:<34} {array_range:<9} ({count} jobs)")
    print(f"Generated {args.ranges_output}")


if __name__ == "__main__":
    main()

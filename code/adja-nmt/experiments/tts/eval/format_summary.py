#!/usr/bin/env python3
"""
Render results/reverse-wer/summary.json into a paste-ready markdown table.

Reads every results/reverse-wer/<run>__<asr>.json (the per-pair detail
files) plus the top-level summary.json, then emits two markdown blocks:

  1. ranked summary table (one row per TTS run; one column per ASR + a
     two-ASR average normalized WER).
  2. per-utterance dump (collapsible <details>) so the thesis appendix can
     reference exact (REF, HYP) pairs.

Usage:
    python experiments/tts/eval/format_summary.py
    python experiments/tts/eval/format_summary.py \\
        --in results/reverse-wer --out results/reverse-wer-summary.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.stdout.reconfigure(line_buffering=True)


HEADER = """\
# Adja TTS Reverse-WER Summary

Auto-generated by `experiments/tts/eval/format_summary.py`. Each row = one TTS
run on `JosueG/adja-tts-results`. Reverse-WER is computed by transcribing
every synthesized WAV with our Adja ASRs and comparing the hypothesis to the
original prompt text — lower error = more intelligible synthesis.

## ASR backends

| Label | Repo | Architecture | Published test CER | Endpoint |
|---|---|---|---|---|
| `c4v2` | [JosueG/wav2vec2-xlsr-adja-c4v2](https://huggingface.co/JosueG/wav2vec2-xlsr-adja-c4v2) | XLS-R 300M + CTC | 25.05% | dedicated, intel-spr x2 |
| `e4v4` | [JosueG/whisper-ewe-adja-e4v4](https://huggingface.co/JosueG/whisper-ewe-adja-e4v4) | Whisper-small fine-tuned | 37.18% (overfit) | dedicated, intel-spr x2 |

E4_v5 (resubmit of the lost original-E4 24.90% checkpoint, HF Job
[`69f0f1c8d2c8bd8662bd235c`](https://huggingface.co/jobs/JosueG/69f0f1c8d2c8bd8662bd235c))
will be added as a third ASR once it lands.

## Conventions

- **Norm**: NFC + lowercase + ASCII-punctuation strip (Adja chars ɛ, ɔ, ŋ, ɖ
  and tone marks preserved). Use for cross-run ranking.
- **Raw**: exact-string comparison (conservative).
- **Median utt CER**: per-utterance median, robust to single-utterance
  Whisper hallucination loops that explode corpus-level WER >500%.

## Ceiling caveat

Our Adja ASRs are weak on real Adja speech (sanity-check normalized CER:
E4v4 ≈ 65%, C4v2 ≈ 70% on a 10-sample test slice). Reverse-WER on TTS
audio inherits that floor — treat numbers as a *relative* TTS quality
signal, not absolute intelligibility. The C4v2 column is more stable than
E4v4 because Whisper hallucinates on out-of-distribution audio (TTS noise,
unfamiliar acoustics) while CTC degrades gracefully. **Recommended
headline metric: C4v2 corpus-level CER (norm) + median utterance CER.**

## Ranked summary

Sorted by **C4v2 corpus CER (norm)** — lower = more intelligible TTS.

"""


def load_pair_files(in_dir: Path) -> list[dict]:
    pairs = []
    for p in sorted(in_dir.glob("*__*.json")):
        if p.name == "summary.json":
            continue
        with open(p, encoding="utf-8") as f:
            pairs.append(json.load(f))
    return pairs


def build_summary_table(pairs: list[dict]) -> str:
    """One row per run × ASR. Includes corpus + median utt metrics.

    Sorted by C4v2 corpus CER norm (the most stable ASR), with E4v4
    rows appearing alongside their corresponding run for visual grouping.
    """
    by_run: dict[str, dict[str, dict]] = {}
    asr_labels: list[str] = []
    for p in pairs:
        run = p["run"]
        label = p["asr_label"]
        by_run.setdefault(run, {})[label] = p["aggregate"]
        if label not in asr_labels:
            asr_labels.append(label)

    if not by_run:
        return "_(no runs scored yet)_\n"

    # Sort runs by C4v2 corpus CER (norm); fall back to first available ASR.
    rank_label = "c4v2" if "c4v2" in asr_labels else asr_labels[0]

    def rank_key(run: str) -> float:
        agg = by_run[run].get(rank_label)
        if agg and agg.get("cer_norm") is not None:
            return agg["cer_norm"]
        return float("inf")

    rows = [
        "| Run | ASR | n | WER raw | WER norm | CER raw | CER norm | Median utt CER norm |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for run in sorted(by_run.keys(), key=rank_key):
        for lbl in asr_labels:
            agg = by_run[run].get(lbl) or {}
            rows.append(
                f"| {run} | `{lbl}` | {_fmt(agg.get('n'))} | "
                f"{_fmt(agg.get('wer_raw'))} | {_fmt(agg.get('wer_norm'))} | "
                f"{_fmt(agg.get('cer_raw'))} | {_fmt(agg.get('cer_norm'))} | "
                f"{_fmt(agg.get('median_utt_cer_norm'))} |"
            )
    return "\n".join(rows) + "\n"


def _fmt(v) -> str:
    if v is None or v == float("inf"):
        return "—"
    if isinstance(v, float):
        return f"{v:.2f}"
    return str(v)


def build_per_utterance(pairs: list[dict]) -> str:
    """Collapsed appendix with REF/HYP pairs per (run, ASR)."""
    out = []
    for p in pairs:
        out.append(f"<details><summary>{p['run']} — {p['asr_label']}</summary>\n")
        out.append(f"\nendpoint: `{p['asr_repo']}`\n")
        out.append("\n| file | REF | HYP | WER raw | WER norm | CER norm |")
        out.append("|---|---|---|---|---|---|")
        for u in p.get("per_utterance", []):
            ref = u["text"].replace("|", "\\|")
            hyp = (u["hyp"] or "").replace("|", "\\|").replace("\n", " ")
            out.append(
                f"| {u['file']} | {ref} | {hyp} | "
                f"{_fmt(u['wer_raw'])} | {_fmt(u['wer_norm'])} | {_fmt(u['cer_norm'])} |"
            )
        out.append("\n</details>\n")
    return "\n".join(out)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--in", dest="in_dir", default="results/reverse-wer")
    p.add_argument("--out", default="results/reverse-wer-summary.md")
    args = p.parse_args()

    in_dir = Path(args.in_dir)
    pairs = load_pair_files(in_dir)
    md = HEADER + build_summary_table(pairs)
    md += (
        "\n## Interpretation notes (2026-04-29 expanded run, n = "
        f"{len(pairs)} run-ASR pairs over {len({p['run'] for p in pairs})} runs)\n\n"
        "- **The Spark family is the clear winner.** T3, T3_spark_120steps_2026-04-18, "
        "and T3_spark_20ep_earlystop_2026-04-18 all sit in the 33–47% C4v2 normalized "
        "CER band — within ~10 points of C4v2's own published test CER on REAL Adja "
        "speech (25.05%). Reverse-WER converges with the listening-test verdict that "
        "*Spark is the only architecture producing intelligible Adja*.\n"
        "- **T1_csm_ewe_stage1 lands at C4v2 CER 56% — and the Ewe Whisper pretraining "
        "is showing through.** The CSM stage-1 model produces intelligible Ewe (per "
        "listening test), and our ASRs (E4v4 has Ewe pretraining, C4v2 has Adja chars "
        "in the vocab) recognize a meaningful fraction of it. The two-ASR average is "
        "the right read: ~53% norm CER.\n"
        "- **CF2 still picks up the one intelligible sentence.** Even with the "
        "expanded run set, the CF2_adja_sent03 sample transcribes at 38% CER on "
        "C4v2 — the same sample the listening test flagged as \"1/5 intelligible "
        "Adja.\" Sample-level reverse-WER is a useful drill-down even when "
        "corpus-level numbers are dominated by noise.\n"
        "- **Stage 2 cross-language attempts (T1_csm_ewe_adja_stage2, T2_orpheus_*_"
        "ewe_adja_stage2*) all sit ≥100% CER.** This matches the listening verdict "
        "(\"all noise except CF2 sample 03\") and is the strongest quantitative evidence "
        "for the Gbe-family-cascade-doesn't-work-without-curriculum-annealing claim.\n"
        "- **T2 Orpheus LoRA family at 200%+ CER is honest noise** — every variant "
        "(r=32, r=64, r=128, full-FT, FR base, EN/FR Stage 2) scores roughly the same "
        "on C4v2 (~200-300% CER). This is the negative-result floor.\n"
        "- **Whisper hallucination on E4v4 explodes some rows above 1000% CER** "
        "(notably T2_orpheus_en_lora_r128, T2_orpheus_fr_lora_r64). These are "
        "auto-regressive repetitive-token loops on out-of-distribution synthesis. "
        "Look at the C4v2 column for these runs; the median utterance CER is also "
        "more robust than corpus CER. This is the main reason we keep two architecturally "
        "different ASRs in the eval.\n"
        "- **Skipped (no scoreable metrics.json):** T6 MMS-Ewe, T7 VoxCPM2, T10 F5, "
        "T11 E2 — all saved training config but no `generated` text↔audio map. T2 "
        "Orpheus zh-Ewe inference run had CUDA-error placeholders instead of audio. "
        "Future TTS runs should always emit a `generated` list of "
        "`{file, text, duration_sec}` records so reverse-WER can score them.\n"
    )
    md += "\n## Per-utterance detail\n\n" + build_per_utterance(pairs) + "\n"

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(md, encoding="utf-8")
    print(f"Wrote {out} ({len(pairs)} run-ASR pairs)")


if __name__ == "__main__":
    main()
